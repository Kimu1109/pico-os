-- pico_test_test.lua が動かすテスト。"[期待NG]" の付いたものはわざと失敗する
test("読み込みとsetup", function()
    local app = load_app()
    eq(app:widget("count").setup, true)
    eq(app:widget("count").data, "hello\n", "フォルダのファイルを読める")
end)
test("タップとフレーム", function()
    local app = load_app()
    app:tap("+1")
    eq(app:widget("count").text, "1")
    app:frame(250)
    eq(app.env.count, 21)
    eq(app:widget("count").dt, 250)
    ok(app:key("enter"))
    eq(app.env.count, 100)
end)
test("サンドボックス", function()
    local app = load_app()
    local s = app.env.SANDBOX
    eq({ s.io, s.dofile, s.package, s.debug, s.exit, s.dump }, {})
    ok(s.time and s.tween, "os.time と pico.* の同梱モジュール")
    raises(function() app.env.setmetatable({}, { __gc = print }) end, "__gc")
    raises(function() app.pico.no_such_api() end, "pico_mock に無い関数です: pico.no_such_api")
end)
test("書き込みは本物のファイルを変えない", function()
    local app = load_app()
    app.pico.sd_write(app.sd_dir .. "/data.txt", "x")
    eq(app.pico.sd_read(app.sd_dir .. "/data.txt"), "x")
    app.pico.sd_remove(app.sd_dir .. "/data.txt")
    eq(app.pico.sd_exists(app.sd_dir .. "/data.txt"), false)
end)
test("setup=false と stubs", function()
    local app = load_app { setup = false, stubs = { battery = function() return 50 end } }
    eq(app:widget("count").setup, nil)
    eq(app.pico.battery(), 50)
end)
test("[期待NG] eq の失敗", function()
    eq({ a = 1, b = { 2 } }, { a = 1, b = { 3 } })
end)
test("[期待NG] アプリのエラー", function()
    local app = load_app()
    app:tap("無いボタン")
end)
